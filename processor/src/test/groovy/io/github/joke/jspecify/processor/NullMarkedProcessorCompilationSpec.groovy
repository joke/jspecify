package io.github.joke.jspecify.processor

import com.google.testing.compile.Compiler
import com.google.testing.compile.JavaFileObjects
import spock.lang.Specification
import spock.lang.Tag

import javax.tools.JavaFileObject
import javax.tools.StandardLocation

import static com.google.testing.compile.CompilationSubject.assertThat

/**
 * End-to-end behaviour through a real javac. The unit contract lives in
 * {@link NullMarkedProcessorSpec}; this spec pins what a consuming compilation actually observes.
 */
@Tag('integration')
class NullMarkedProcessorCompilationSpec extends Specification {

    static final String EXPECTED_CONTENT = '// Generated by io.github.joke.jspecify - do not edit.\n' +
            '@org.jspecify.annotations.NullMarked\n' +
            'package com.example;\n'

    static JavaFileObject type(String pkg, String name) {
        JavaFileObjects.forSourceString("${pkg}.${name}", "package ${pkg};\npublic class ${name} {}\n")
    }

    static Compiler compiler() {
        Compiler.javac().withProcessors(new NullMarkedProcessor())
    }

    static List<String> generatedPackageInfos(compilation) {
        compilation.generatedSourceFiles()*.name.findAll { it.contains('package-info') }
    }

    def 'generates a package-info for a package that has none'() {
        when:
        def compilation = compiler().compile(type('com.example', 'Foo'))

        then:
        assertThat(compilation).succeeded()
        assertThat(compilation).generatedSourceFile('com.example.package-info')
                .contentsAsUtf8String().isEqualTo(EXPECTED_CONTENT)
    }

    def 'generates exactly one package-info for many types in one package'() {
        when:
        def compilation = compiler().compile(type('com.example', 'Foo'),
                type('com.example', 'Bar'),
                type('com.example', 'Baz'))

        then:
        assertThat(compilation).succeeded()

        expect:
        generatedPackageInfos(compilation).size() == 1
    }

    def 'generates a package-info for each nested package'() {
        when:
        def compilation = compiler().compile(type('com.example', 'Foo'), type('com.example.inner', 'Bar'))

        then:
        assertThat(compilation).succeeded()

        expect:
        generatedPackageInfos(compilation).sort() == [
                '/SOURCE_OUTPUT/com/example/inner/package-info.java',
                '/SOURCE_OUTPUT/com/example/package-info.java',
        ]
    }

    def 'leaves a package that already declares a package-info alone'() {
        def existing = JavaFileObjects.forSourceString('com.example.package-info', declaration)

        when:
        def compilation = compiler().compile(type('com.example', 'Foo'), existing)

        then:
        assertThat(compilation).succeeded()

        expect:
        generatedPackageInfos(compilation).empty

        where:
        declaration << [
                '@org.jspecify.annotations.NullMarked\npackage com.example;\n',
                '@org.jspecify.annotations.NullUnmarked\npackage com.example;\n',
                '/** Javadoc only, no annotation at all. */\npackage com.example;\n',
        ]
    }

    def 'leaves a package whose package-info is already on the classpath alone'() {
        // This spec's own package ships a hand-written package-info.class on the test classpath.
        when:
        def compilation = compiler().compile(type('io.github.joke.jspecify.processor', 'Probe'))

        then:
        assertThat(compilation).succeeded()

        expect:
        generatedPackageInfos(compilation).empty
    }

    def 'emits the package-info into the class output carrying the annotation'() {
        when:
        def compilation = compiler().compile(type('com.example', 'Foo'))

        then:
        assertThat(compilation).succeeded()

        expect:
        compilation.generatedFile(StandardLocation.CLASS_OUTPUT, 'com/example/package-info.class').present
    }

    def 'never claims the annotations it matches'() {
        def observer = new AnnotationObservingProcessor()
        def source = JavaFileObjects.forSourceString('com.example.Foo',
                'package com.example;\n@Deprecated\npublic class Foo {}\n')

        when:
        def compilation = Compiler.javac()
                .withProcessors(new NullMarkedProcessor(), observer)
                .compile(source)

        then:
        assertThat(compilation).succeeded()

        expect:
        observer.sawAnnotatedElements
    }

    def 'covers a package introduced by another processor in a later round'() {
        when:
        def compilation = Compiler.javac()
                .withProcessors(new NullMarkedProcessor(), new TypeGeneratingProcessor())
                .compile(type('com.example', 'Foo'))

        then:
        assertThat(compilation).succeeded()

        expect:
        generatedPackageInfos(compilation).sort() == [
                '/SOURCE_OUTPUT/com/example/package-info.java',
                '/SOURCE_OUTPUT/com/generated/package-info.java',
        ]
    }

    def 'compiles cleanly under -Werror'() {
        when:
        def compilation = compiler().withOptions('-Werror').compile(type('com.example', 'Foo'))

        then:
        assertThat(compilation).succeeded()
        assertThat(compilation).hadWarningCount(0)
    }

    def 'warns and skips a type in the default package'() {
        def source = JavaFileObjects.forSourceString('Foo', 'public class Foo {}\n')

        when:
        def compilation = compiler().compile(source)

        then:
        assertThat(compilation).succeeded()
        assertThat(compilation).hadWarningContaining('default package cannot be null-marked')

        expect:
        generatedPackageInfos(compilation).empty
    }

    def 'errors clearly when JSpecify is not on the compile classpath'() {
        when:
        def compilation = compiler().withClasspath([]).compile(type('com.example', 'Foo'))

        then:
        assertThat(compilation).failed()
        assertThat(compilation).hadErrorContaining('Add a compile dependency on org.jspecify:jspecify')
    }

    // The module rule (a @NullMarked module-info suppresses all generation) has no spec here:
    // compile-testing's in-memory file manager is not module-aware, so a modular compilation cannot
    // be driven through it. The rule is covered by unit specs, and end-to-end by the spike harness
    // recorded in the change's design.md, which ran it through a real Gradle/javac build.

    def 'declares itself as an aggregating processor for Gradle'() {
        expect:
        getClass().getResource('/META-INF/gradle/incremental.annotation.processors').text.trim() ==
                'io.github.joke.jspecify.processor.NullMarkedProcessor,AGGREGATING'
    }
}
